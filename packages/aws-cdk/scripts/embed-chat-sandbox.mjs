#!/usr/bin/env node

// Embeds scripts/chat-sandbox into the construct so the sandbox host can build
// the chat image for its own architecture at boot. The published package has no
// access to the repository, so the files travel inside the compiled library.

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const sourceDir = resolve(fileURLToPath(new URL("../../../scripts/chat-sandbox", import.meta.url)));
const targetFile = resolve(fileURLToPath(new URL("../src/chat-sandbox-image.ts", import.meta.url)));
const names = ["Dockerfile", "git-credential.mjs"];

const files = {};
const hash = createHash("sha256");
for (const name of names) {
  const content = await readFile(resolve(sourceDir, name), "utf8");
  files[name] = content;
  hash.update(`${name}\0${content}\0`);
}

const updated = `// Generated by scripts/embed-chat-sandbox.mjs from scripts/chat-sandbox. Do not edit.

/** Build context for the Workspace chat image, built on the sandbox host at boot. */
export const CHAT_SANDBOX_BUILD_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)};

/** Content-addressed tag: a changed build context means a new image and a new host. */
export const CHAT_SANDBOX_IMAGE = "ctxpipe-chat-sandbox:${hash.digest("hex").slice(0, 12)}";
`;

let current = "";
try {
  current = await readFile(targetFile, "utf8");
} catch {
  // First run.
}
if (current !== updated) {
  await writeFile(targetFile, updated);
  console.log(`Embedded chat sandbox build context into ${targetFile}`);
}
